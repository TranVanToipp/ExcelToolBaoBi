using System;

namespace ExcelTool.Models.Pricing
{
    public class BomSetting
    {
        // =========================================================
        // ID
        // =========================================================

        public int Id { get; set; }


        // =========================================================
        // LOẠI SẢN PHẨM
        // Ví dụ:
        // Tờ rơi
        // Túi xách
        // Brochure gấp 3
        // Folder gấp đôi
        // =========================================================

        public string ProductType { get; set; } = "";


        // =========================================================
        // QUY CÁCH
        // Ví dụ:
        // DxR
        // DxRxC
        // DxRxTai
        // =========================================================

        public string Specification { get; set; } = "";


        // =========================================================
        // CÔNG THỨC
        // Ví dụ:
        // D*R
        // 2DxR
        // 2D x (R+tai)
        // 3D x (R+tai)
        // =========================================================

        public string Formula { get; set; } = "";


        // =========================================================
        // LOẠI IN
        // Ví dụ:
        // In Offset thường
        // =========================================================

        public string PrintingType { get; set; } = "";


        // =========================================================
        // CÔNG ĐOẠN 1
        // Ví dụ:
        // Bế tay
        // =========================================================

        public string Process1 { get; set; } = "";


        // =========================================================
        // CÔNG ĐOẠN 2
        // Ví dụ:
        // Dán túi xách
        // Dán tay
        // =========================================================

        public string Process2 { get; set; } = "";


        // =========================================================
        // THỨ TỰ
        // =========================================================

        public int SortOrder { get; set; }
    }
}